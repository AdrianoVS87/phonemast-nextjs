#!/usr/bin/env node
/**
 * Writes src/lib/page-dates.ts: the date of the last change to each page's source file.
 * The sitemap uses these dates for <lastmod>, because Google only uses lastmod when it is
 * "consistently and verifiably accurate". Run before committing page changes:
 *   node scripts/generate-page-dates.mjs
 * Files with uncommitted changes get today's date.
 */
import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const ROUTES = {
  "/": "src/app/page.tsx",
  "/about-us": "src/app/about-us/page.tsx",
  "/team": "src/app/team/page.tsx",
  "/contact": "src/app/contact/page.tsx",
  "/faq": "src/app/faq/page.tsx",
  "/handbook": "src/app/handbook/page.tsx",
  "/blog": "src/app/blog/page.tsx",
  "/phone-mast-rent-2026": "src/app/phone-mast-rent-2026/page.tsx",
  "/phone-mast-lease-2026": "src/app/phone-mast-lease-2026/page.tsx",
  "/phone-mast-solicitors": "src/app/phone-mast-solicitors/page.tsx",
  "/electronic-communications-code": "src/app/electronic-communications-code/page.tsx",
  "/section-26-notice": "src/app/section-26-notice/page.tsx",
  "/phone-mast-services": "src/app/phone-mast-services/page.tsx",
  "/phone-mast-services/rent-reviews": "src/app/phone-mast-services/rent-reviews/page.tsx",
  "/phone-mast-services/lease-renewals": "src/app/phone-mast-services/lease-renewals/page.tsx",
  "/phone-mast-services/new-lettings": "src/app/phone-mast-services/new-lettings/page.tsx",
  "/phone-mast-services/mast-sales": "src/app/phone-mast-services/mast-sales/page.tsx",
  "/phone-mast-services/removal-and-redevelopment": "src/app/phone-mast-services/removal-and-redevelopment/page.tsx",
  "/phone-mast-services/electricity-costs-recovery": "src/app/phone-mast-services/electricity-costs-recovery/page.tsx",
  "/phone-mast-services/other-services": "src/app/phone-mast-services/other-services/page.tsx",
  "/phone-mast-services/lease-retrievals": "src/app/phone-mast-services/lease-retrievals/page.tsx",
  "operator": "src/app/[operator]/page.tsx",
  "location": "src/app/locations/[location]/page.tsx",
};

const sh = (cmd) => execSync(cmd, { encoding: "utf8" }).trim();
const today = new Date().toISOString().slice(0, 10);
const dirty = new Set(sh("git status --porcelain").split("\n").filter(Boolean).map((l) => l.slice(3).replace(/"/g, "")));

const out = {};
for (const [route, file] of Object.entries(ROUTES)) {
  if (dirty.has(file) || [...dirty].some((d) => d.endsWith("/") && file.startsWith(d))) {
    out[route] = today;
    continue;
  }
  const d = sh(`git log -1 --format=%cs -- "${file}"`);
  out[route] = d || today;
}

const body = `// Generated by scripts/generate-page-dates.mjs. Do not edit by hand.
// Date of the last change to each page's source file, used for sitemap <lastmod>.
export const PAGE_DATES: Record<string, string> = ${JSON.stringify(out, null, 2)};
`;
writeFileSync("src/lib/page-dates.ts", body);
console.log(out);
